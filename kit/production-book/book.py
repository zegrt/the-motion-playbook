#!/usr/bin/env python3
"""book.py: one production's book, as small `key: value` records in book/records/, with its pages generated from them.

No state depends on the order of the records: the current version is the highest number, a version is approved when
an approval names it, and a note is open until a record with its id closes it. Paths are relative to the project
folder (the book folder's parent). Commands: new, log, build, status, check, close; see README.md beside this file.
Standard library only.
"""
import argparse, datetime, getpass, os, re, sys

KINDS = ('unit', 'version', 'approval', 'note', 'decision')
REQUIRED = {'unit': ('id', 'title', 'date'), 'version': ('id', 'unit', 'step', 'pass', 'output', 'summary', 'date'),
            'approval': ('version', 'quote', 'by', 'medium', 'date'), 'note': ('id', 'unit', 'text', 'date'),
            'decision': ('scope', 'words', 'by', 'date')}
NOTE_TYPES, CLOSING, DEFAULT_STEPS = ('review', 'cross-unit', 'handoff', 'lesson'), ('closed', 'parked', 'wontfix'), \
    'board,look,layout,anim,finish,sound,deliver'
GEN_START, GEN_END = '<!-- generated by book.py build: edit the records, not this block -->', \
    '<!-- end of the generated block -->'
HERE = os.path.dirname(os.path.abspath(__file__))
LOG_HELP = '''kinds and their fields (* required; date and by are filled in):
  unit      id* title* type (shot, state, artboard, deliverable) owner steps joins format length variant language
  version   unit* step* pass* (rough, final) output* summary* checked limits affects from   (id is numbered)
  approval  version* quote* (the director's words) by* medium*   (it approves exactly that version)
  note      unit* text* version frames priority (must, should) type (review, cross-unit, handoff, lesson)
            (id is numbered; to close a note, log it again with its id and state=closed, parked or wontfix)
  decision  scope* words* (the director's own) by* source
A record can also be written by hand: see "What's in a book" in README.md beside book.py.'''


def slurp(path):
    with open(path, encoding='utf-8') as f:
        return f.read()


def put(path, text):
    with open(path, 'w', encoding='utf-8', newline='\n') as f:
        f.write(text)


def parse(text):
    """key: value lines; a line starting with whitespace continues the value above; # comments and blanks skipped."""
    rec, last = {}, None
    for line in text.splitlines():
        if not line.strip() or line.lstrip().startswith('#'):
            continue
        if line[0] in ' \t' and last:
            rec[last] += ' ' + line.strip()
        elif ':' not in line:
            raise ValueError(f'not a "key: value" line: {line!r}')
        else:
            k, v = line.split(':', 1)
            last = k.strip().lower()
            rec[last] = v.strip()
    return rec


def dump(rec):
    return ''.join(f'{k}: {v}\n' for k, v in rec.items() if not k.startswith('_'))


def now():
    return datetime.datetime.now().strftime('%Y-%m-%dT%H:%M')


class Book:
    def __init__(self, path):
        self.dir = os.path.abspath(path)
        if not os.path.isfile(os.path.join(self.dir, 'book.txt')):
            sys.exit(f'No book at {self.dir} (no book.txt). Make one with: book.py new {path} --title ... --units ...')
        self.root, self.conf = os.path.dirname(self.dir), parse(slurp(os.path.join(self.dir, 'book.txt')))
        self.steps = [s.strip() for s in self.conf.get('steps', DEFAULT_STEPS).split(',') if s.strip()]
        self.records, self.problems, rdir = [], [], os.path.join(self.dir, 'records')
        for f in os.listdir(rdir) if os.path.isdir(rdir) else []:
            try:
                if f.endswith('.txt'):
                    self.records.append({**parse(slurp(os.path.join(rdir, f))), '_file': f})
            except (ValueError, UnicodeDecodeError) as e:
                self.problems.append(f'records/{f}: {e}')

    def of(self, kind):
        return [r for r in self.records if r.get('kind') == kind]

    def units(self):
        return {r.get('id'): r for r in self.of('unit')}

    def unit_steps(self, u):
        return [s.strip() for s in u.get('steps', ','.join(self.steps)).split(',') if s.strip()]


def vnum(vid):
    m = re.search(r'_v(\d+)$', vid or '')
    return int(m.group(1)) if m else -1


def versions(book, unit, step):
    """One unit and step's versions by number; the last is current."""
    return sorted((v for v in book.of('version') if (v.get('unit'), v.get('step')) == (unit, step)),
                  key=lambda v: vnum(v.get('id')))


def approvals_of(book, vid):
    return [a for a in book.of('approval') if a.get('version') == vid]


def notes(book):
    """Each note id: its opening record, with its closing record's state if it has one. Order plays no part."""
    out = {r.get('id'): dict(r, state='open') for r in book.of('note') if r.get('state', 'open') == 'open'}
    for r in book.of('note'):
        if r.get('state') in CLOSING and r.get('id') in out:
            out[r['id']]['state'] = r['state']
    return out


def validate(book, r):
    """Every rule a record must meet: log refuses a record that breaks one, check reports it. (errors, warnings)"""
    kind, e, w = r.get('kind'), [], []
    if kind not in KINDS:
        return [f'kind "{kind}" is not one of {", ".join(KINDS)}'], []
    missing = [k for k in REQUIRED[kind] if not r.get(k)]
    if missing:
        e.append(f'{"an" if kind[0] in "aeiou" else "a"} {kind} needs {", ".join(missing)}'
                 + {'approval': " (the director's words go in quote: agents record approvals, only the director gives "
                                'them)', 'decision': " (the director's own words go in words: a recommendation is a "
                                                       'note, not a decision)'}.get(kind, ''))
    rest = [x for x in book.records if x is not r]
    twin = next((x for x in rest if kind == 'unit' and x.get('kind') == 'unit' and x.get('id') == r.get('id')), None)
    if twin:
        e.append(f'unit id {r["id"]} is used twice (also in records/{twin["_file"]}): one record per unit; '
                 'edit that one')
    if kind in ('version', 'note') and r.get('unit') and r['unit'] not in book.units():
        e.append(f'unknown unit {r["unit"]}')
    if kind == 'version':
        want = f"{r.get('unit', '').lower()}_{r.get('step', '')}_v"
        if r.get('step') and r['step'] not in book.steps:
            e.append(f'step "{r["step"]}" is not one of this book\'s steps ({", ".join(book.steps)})')
        if r.get('pass') and r['pass'] not in ('rough', 'final'):
            e.append(f'pass "{r["pass"]}" is not rough or final')
        if r.get('id') and not re.fullmatch(re.escape(want) + r'\d{3}', r['id']):
            e.append(f'version id {r["id"]} should be {want}### (unit, step, three digits)')
        if r.get('id') and any(x.get('kind') == 'version' and x.get('id') == r['id'] for x in rest):
            e.append(f'version id {r["id"]} is used twice; never reuse one')
        if not r.get('checked'):
            w.append(f'version {r.get("id")} says nothing in "checked" (what was checked, at which level)')
    if kind == 'approval' and r.get('version') and not any(v.get('id') == r['version'] for v in book.of('version')):
        e.append(f'approval of {r["version"]}, which no version record has')
    if kind == 'note':
        state = r.get('state', 'open')
        same = [x for x in rest if x.get('kind') == 'note' and x.get('id') == r.get('id')]
        opened = any(x.get('state', 'open') == 'open' for x in same)
        closed = any(x.get('state') in CLOSING for x in same)
        if r.get('type', 'review') not in NOTE_TYPES or r.get('priority', 'should') not in ('must', 'should'):
            e.append(f'type must be one of {", ".join(NOTE_TYPES)}, and priority must or should')
        if state not in ('open',) + CLOSING:
            e.append(f'note state "{state}" is not open, {", ".join(CLOSING)}')
        elif state == 'open' and (opened or (closed and r not in book.records)):  # a new record can't reopen a note
            e.append(f'note id {r.get("id")} is already ' + ('closed, and closed stays closed' if closed else 'used')
                     + ': a new note needs a new id')
        elif state in CLOSING and (not opened or closed):
            e.append(f'note {r.get("id")} is ' + ('closed twice: keep one closing record' if closed else
                                                  'closed here but never opened'))
    return e, w


def table(head, rows):
    out = '| ' + ' | '.join(head) + ' |\n|' + '---|' * len(head) + '\n'
    return out + ''.join('| ' + ' | '.join(str(c).replace('|', '/') for c in r) + ' |\n' for r in rows)


def front_tables(book):
    rows = []
    for uid, u in sorted(book.units().items()):
        for st in book.unit_steps(u):
            vers = versions(book, uid, st)
            if vers:
                oks = sorted(approvals_of(book, vers[-1].get('id')), key=lambda a: (a.get('date', ''), a.get('quote')))
                prior = [v.get('id') for v in vers[:-1] if approvals_of(book, v.get('id'))]
                said = '; '.join(f"{a.get('by')}, {a.get('date', '')[:10]}: \"{a.get('quote')}\"" for a in oks)
                rows.append([uid, st, vers[-1].get('id'), f"approved ({vers[-1].get('pass')})" if oks else
                             'not approved yet', said or (f'last approved: {prior[-1]}' if prior else '')])
    out = '## Where every unit stands\n\n' + (table(['Unit', 'Step', 'Current', 'Status', 'Approved by'], rows)
                                              if rows else 'No versions yet.\n')
    n_open = sum(1 for n in notes(book).values() if n['state'] == 'open' and n.get('type') != 'lesson')
    out += (f'\nOpen items: {n_open} (see [OPEN.md](OPEN.md)). '
            f'Decisions: {len(book.of("decision"))} (see [DECISIONS.md](DECISIONS.md)).\n')
    dlv = sorted((u for u in book.units().values() if u.get('type') == 'deliverable'), key=lambda u: u.get('id'))
    return out + ('\n## Deliverables\n\n' + table(['Deliverable', 'Format', 'Length', 'Variant', 'Language'], [
        [u.get(k, '') for k in ('id', 'format', 'length', 'variant', 'language')] for u in dlv]) if dlv else '')


def open_page(book):
    out = ('# Open items\n\n' + GEN_START + '\n\nThe one open list. Add to it with `book.py log note`; close an '
           'item by logging its id again\nwith `state=closed`, `parked` or `wontfix`.\n')
    for uid, u in sorted(book.units().items()):
        mine = sorted((n for n in notes(book).values() if n.get('unit') == uid and n.get('type') != 'lesson'),
                      key=lambda n: n.get('id', ''))
        groups = [('Must', [n for n in mine if n['state'] == 'open' and n.get('priority') == 'must']),
                  ('Should', [n for n in mine if n['state'] == 'open' and n.get('priority') != 'must']),
                  ('Parked', [n for n in mine if n['state'] == 'parked'])]
        out += f"\n## {uid} {u.get('title', '')}\n" if any(g for _, g in groups) else ''
        for label, group in (g for g in groups if g[1]):
            out += f'\n{label}:\n'
            for n in group:
                where = ', '.join(x for x in (n.get('version', ''), n.get('frames', '')) if x)
                kind = '' if n.get('type', 'review') == 'review' else f" [{n.get('type')}]"
                out += f"- {n.get('id')}{kind}{' (' + where + ')' if where else ''}: {n.get('text')}\n"
    return out + '\n' + GEN_END + '\n'


def decisions(book):
    return sorted(book.of('decision'), key=lambda d: (d.get('date', ''), d.get('scope', '')))  # for reading, by date


def rendered(book):
    front = os.path.join(book.dir, 'BOOK.md')
    text = slurp(front) if os.path.exists(front) else f"# {book.conf.get('title', 'Book')}\n"
    block = GEN_START + '\n\n' + front_tables(book).rstrip('\n') + '\n\n' + GEN_END
    if GEN_START in text and GEN_END in text:
        text = text[:text.index(GEN_START)] + block + text[text.index(GEN_END) + len(GEN_END):]
    else:
        text = text.rstrip('\n') + '\n\n' + block + '\n'
    rows = [[d.get('date', '')[:10], d.get('scope'), f"\"{d.get('words')}\"", d.get('by'), d.get('source', '')]
            for d in decisions(book)]
    dec = ('# Decisions\n\n' + GEN_START + "\n\nOnly the director decides; these are their words. A recommendation is "
           'a note, not a decision.\n\n' + (table(['Date', 'Scope', "Director's words", 'By', 'Source'], rows)
                                             if rows else 'None yet.\n') + '\n' + GEN_END + '\n')
    return {'BOOK.md': text, 'OPEN.md': open_page(book), 'DECISIONS.md': dec}


def check(book, today=None):
    errors, warnings = list(book.problems), []
    for r in sorted(book.records, key=lambda r: r['_file']):  # sorted only to print the same way each time
        e, w = validate(book, r)
        errors += [f'records/{r["_file"]}: {x}' for x in e]
        warnings += [f'records/{r["_file"]}: {x}' for x in w]
    for uid, u in sorted(book.units().items()):
        for st in book.unit_steps(u):
            v = (versions(book, uid, st) or [None])[-1]
            if v and not os.path.exists(os.path.join(book.root, v.get('output', ''))):
                errors.append(f'{uid} {st}: the current version {v.get("id")} has no output at {v.get("output")}')
    today, days = today or datetime.date.today().isoformat(), int(book.conf.get('note_days', '14'))
    for n in notes(book).values():
        age = (datetime.date.fromisoformat(today) - datetime.date.fromisoformat(n.get('date', today)[:10])).days
        if n['state'] == 'open' and n.get('type') != 'lesson' and age > days:
            warnings.append(f'note {n.get("id")} has been open {age} days (over {days}): close it, park it or decide')
    warnings += [f'{name} is out of date with the records: run build' for name, text in rendered(book).items()
                 if not os.path.exists(os.path.join(book.dir, name)) or slurp(os.path.join(book.dir, name)) != text]
    return errors, warnings


def who(by=None):
    return by or os.environ.get('BOOK_BY') or getpass.getuser()


def cmd_new(a):
    path, tdir = os.path.abspath(a.path), os.path.join(HERE, 'templates')
    if os.path.exists(path) and os.listdir(path):
        sys.exit(f'{path} exists and is not empty; new never overwrites a book.')
    ids = [spec.partition(' ')[0] for spec in a.units]
    if len(set(ids)) < len(ids):
        sys.exit(f'unit id {next(i for i in ids if ids.count(i) > 1)} is given twice; one record per unit.')
    os.makedirs(os.path.join(path, 'records'))
    os.makedirs(os.path.join(path, 'units'))
    put(os.path.join(path, 'book.txt'), dump({'title': a.title, 'kind': a.kind, 'steps': a.steps, 'note_days': '14'}))
    for name in ('BOOK.md', 'LOOK.md', 'CUT.tsv'):
        put(os.path.join(path, name), slurp(os.path.join(tdir, name)).replace('{title}', a.title))
    for uid, _, title in (spec.partition(' ') for spec in a.units):
        put(os.path.join(path, 'units', f'{uid}.md'),
            slurp(os.path.join(tdir, 'UNIT.md')).replace('{id}', uid).replace('{title}', title or uid))
        put(os.path.join(path, 'records', f'unit-{uid}.txt'), dump({'kind': 'unit', 'id': uid, 'title': title or uid,
                                                                   'type': 'shot', 'owner': who(a.by),
                                                                   'date': a.date or now()}))
    build(Book(path))
    print(f'Next: write "Now" in BOOK.md and the look in LOOK.md, then log work as it happens.')


def cmd_log(a):
    book = Book(a.book)
    if a.kind not in KINDS or any('=' not in kv for kv in a.fields):
        sys.exit(f'Usage: log KIND key=value ... (KIND is one of {", ".join(KINDS)}); see log --help')
    rec = {'kind': a.kind, **{k.strip().lower(): v.strip() for k, v in (kv.split('=', 1) for kv in a.fields)}}
    rec.setdefault('date', a.date or now())
    rec.setdefault('by', who(a.by))
    if a.kind == 'version' and 'id' not in rec:
        top = max([vnum(v['id']) for v in versions(book, rec.get('unit'), rec.get('step'))], default=0)
        rec['id'] = f"{rec.get('unit', '').lower()}_{rec.get('step', '')}_v{top + 1:03d}"
    if a.kind == 'note' and 'id' not in rec:
        nums = [int(m.group(1)) for r in book.of('note') for m in [re.match(r'N-(\d+)$', r.get('id', ''))] if m]
        rec['id'] = f'N-{max(nums, default=0) + 1:03d}'
    errors, _ = validate(book, rec)
    if errors:
        sys.exit('Not logged: ' + '; '.join(errors) + '.')
    about = rec.get('id') or rec.get('version') or rec.get('scope', 'book')
    name, n = re.sub(r'[^\w.-]', '_', f'{a.kind}-{about}'), 1
    while os.path.exists(os.path.join(book.dir, 'records', name + (f'-{n}' if n > 1 else '') + '.txt')):
        n += 1
    path = os.path.join(book.dir, 'records', name + (f'-{n}' if n > 1 else '') + '.txt')
    put(path, dump(rec))
    build(Book(a.book), quiet=True)
    print(f'Logged {a.kind} {about} in records/{os.path.basename(path)}; pages rebuilt.')


def build(book, quiet=False):
    for name, text in rendered(book).items():
        put(os.path.join(book.dir, name), text)
    if not quiet:
        print(f'Built BOOK.md, OPEN.md and DECISIONS.md in {book.dir}')


def cmd_check(a):
    book = Book(a.book)
    errors, warnings = check(book, a.today)
    print(''.join(f'error: {e}\n' for e in errors) + ''.join(f'warning: {w}\n' for w in warnings)
          + f'{len(errors)} error(s), {len(warnings)} warning(s); {len(book.records)} records')
    sys.exit(1 if errors else 0)


def cmd_close(a):
    book = Book(a.book)
    errors, date = check(book, a.today)[0], a.today or datetime.date.today().isoformat()
    if errors:
        sys.exit('Fix the check errors before closing:\n  ' + '\n  '.join(errors))
    os.makedirs(a.inbox, exist_ok=True)
    out = os.path.join(a.inbox, f"{date}-{re.sub(r'[^a-z0-9]+', '-', book.conf.get('title', '').lower()).strip('-')}"
                                f"-book-close.md")
    if os.path.exists(out):
        sys.exit(f'{out} exists; close writes it once.')
    lessons = sorted((n for n in notes(book).values() if n.get('type') == 'lesson'), key=lambda n: n.get('id', ''))
    put(out, f"# {book.conf.get('title')}: decisions and lessons at the close\n\n**From:** {who(a.by)}, {date}, by "
             "`book.py close`.\n\n**What it changes:** nothing yet. Material for the wrap's step 2: sort each item "
             'into a project truth (stays in the book) or a craft candidate (a proposal of its own, in the inbox '
             'format).\n\n## Decisions\n\n'
             + (''.join(f"- {d.get('date', '')[:10]}, {d.get('scope')}: \"{d.get('words')}\" ({d.get('by')}; "
                        f"{d.get('source', 'no source')})\n" for d in decisions(book)) or 'None.\n')
             + '\n## Lessons\n\n' + (''.join(f"- {n.get('id')}, {n.get('unit')}: {n.get('text')}\n"
                                             for n in lessons) or 'None.\n'))
    print(f'Wrote {out}. Next: the wrap.')


def main(argv=None):
    ap = argparse.ArgumentParser(prog='book.py', description=__doc__.split('\n')[0])
    sub = ap.add_subparsers(dest='cmd', required=True)
    cmds = {'new': cmd_new, 'log': cmd_log, 'build': lambda a: build(Book(a.book)), 'check': cmd_check,
            'status': lambda a: print(Book(a.book).conf.get('title', 'Book') + '\n\n' + front_tables(Book(a.book))),
            'close': cmd_close}
    p = {}
    for name, fn in cmds.items():
        p[name] = sub.add_parser(name, **({'formatter_class': argparse.RawDescriptionHelpFormatter, 'epilog': LOG_HELP}
                                          if name == 'log' else {}))
        p[name].set_defaults(fn=fn)
        p[name].add_argument('--by', help='who is writing (default: $BOOK_BY or the login name)')
        if name != 'new':
            p[name].add_argument('--book', default='book', help='the book folder (default: ./book)')
    p['new'].add_argument('path')
    p['new'].add_argument('--title', required=True)
    p['new'].add_argument('--units', nargs='+', default=[])
    p['new'].add_argument('--kind', default='linear', choices=('linear', 'interactive', 'still', 'campaign'))
    p['new'].add_argument('--steps', default=DEFAULT_STEPS)
    p['log'].add_argument('kind', help='one of: ' + ', '.join(KINDS))
    p['log'].add_argument('fields', nargs='*', help='key=value pairs (see below)')
    for name in ('new', 'log'):
        p[name].add_argument('--date', help='YYYY-MM-DDTHH:MM (default: now)')
    for name in ('check', 'close'):
        p[name].add_argument('--today', help='YYYY-MM-DD, for repeatable checks')
    p['close'].add_argument('--inbox', required=True)
    a = ap.parse_args(argv)
    a.fn(a)


if __name__ == '__main__':
    main()
